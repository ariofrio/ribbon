// Regenerates the picker's icon catalog from Hugeicons' published index,
// keeping every icon the free package actually exports, including numbered
// variants.
// The output is committed so builds and CI never touch the network.
// Usage: npm run build:catalog  (npm run check:catalog reports drift without writing)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as freeIcons from "@hugeicons/core-free-icons";

const INDEX_URL = "https://hugeicons.com/api/icons";

// These malformed index names resolve to the same package exports as the
// canonical arrow-down-01 and arrow-up-01 records. They are duplicate metadata
// rows, not additional glyphs; Hugeicons' source tree contains only the
// canonical filenames.
const DUPLICATE_INDEX_ALIASES = new Set([
  "arrow-down-0-1",
  "arrow-up-0-1",
]);

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function exportName(iconName) {
  return `${iconName
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("")}Icon`;
}

const response = await fetch(INDEX_URL);
if (!response.ok) {
  throw new Error(`Icon index request failed (${response.status})`);
}
const { icons } = await response.json();

const catalog = icons
  .filter(
    (icon) =>
      !DUPLICATE_INDEX_ALIASES.has(icon.name) &&
      exportName(icon.name) in freeIcons,
  )
  .map((icon) => ({
    name: icon.name,
    export: exportName(icon.name),
    category: icon.category,
    // The index stores tags as one comma-separated string. Names already carry
    // their own words, so keep only the tags that add a synonym.
    tags: [
      ...new Set(
        String(icon.tags ?? "")
          .split(",")
          .map((tag) => tag.trim().toLowerCase())
          .filter(Boolean),
      ),
    ]
      .filter((tag) => !icon.name.split("-").includes(tag))
      .slice(0, 8),
  }))
  .sort((left, right) => left.name.localeCompare(right.name));

const seen = new Set();
for (const entry of catalog) {
  if (seen.has(entry.export)) throw new Error(`duplicate ${entry.export}`);
  seen.add(entry.export);
}

const catalogPath = resolve(root, "src", "icon-catalog.json");

// The index is unversioned and sends no ETag, so the only way to learn that
// Hugeicons rewrote something is to derive the catalog again and compare. This
// reports that without touching the committed files, so drift can be reviewed
// before it is adopted.
if (process.argv.includes("--check")) {
  const committed = JSON.parse(readFileSync(catalogPath, "utf8"));
  const shape = ({ category, tags }) => JSON.stringify({ category, tags });
  const before = new Map(committed.map((entry) => [entry.name, entry]));
  const after = new Map(catalog.map((entry) => [entry.name, entry]));
  const changed = [...after.keys()].filter(
    (name) =>
      before.has(name) && shape(before.get(name)) !== shape(after.get(name)),
  );
  const added = [...after.keys()].filter((name) => !before.has(name));
  const removed = [...before.keys()].filter((name) => !after.has(name));

  if (changed.length === 0 && added.length === 0 && removed.length === 0) {
    console.log(`Catalog matches the index (${catalog.length} icons).`);
    process.exit(0);
  }
  for (const name of changed) {
    console.log(`changed ${name}`);
    console.log(`  committed ${JSON.stringify(before.get(name).tags)}`);
    console.log(`  index     ${JSON.stringify(after.get(name).tags)}`);
  }
  for (const name of added) console.log(`added   ${name}`);
  for (const name of removed) console.log(`removed ${name}`);
  console.log(
    `\n${changed.length} changed, ${added.length} added, ${removed.length} removed. Run npm run build:catalog to adopt.`,
  );
  process.exit(1);
}

writeFileSync(
  catalogPath,
  `${JSON.stringify(catalog, null, 1)}\n`,
);

const imports = catalog.map((entry) => `  ${entry.export},`).join("\n");
const entries = catalog
  .map((entry) => `  ${JSON.stringify(entry.name)}: ${entry.export},`)
  .join("\n");
writeFileSync(
  resolve(root, "src", "icon-catalog.generated.ts"),
  `// Generated by scripts/build-icon-catalog.mjs. Do not edit.
import type { IconSvgElement } from "@hugeicons/react";
import {
${imports}
} from "@hugeicons/core-free-icons";

export const CATALOG_ICONS: Record<string, IconSvgElement> = {
${entries}
};
`,
);

const byCategory = {};
for (const entry of catalog) {
  byCategory[entry.category] = (byCategory[entry.category] ?? 0) + 1;
}
console.log(`Wrote ${catalog.length} icons across ${Object.keys(byCategory).length} categories.`);
